import {readFileSync} from "node:fs";
import test from "node:test";
import assert from "node:assert/strict";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
test("Real bookmaker consensus: no invented model, cross-snapshot mixing or post-event quotes",()=>{
 const x=read("src/lib/research/market-reference.ts");
 assert.match(x,/buildPrematchMarketReference/);
 assert.match(x,/isExactEplFixture/);
 assert.match(x,/e\.event\.status==="scheduled"/);
 assert.match(x,/q\.marketKey!=="soccer_epl\.h2h"/);
 assert.match(x,/q\.line!==undefined/);
 assert.match(x,/q\.suspended===true/);
 assert.match(x,/now-at>MAX_QUOTE_AGE_MS/);
 assert.match(x,/at>=Date\.parse\(e\.event\.startsAt\)/);
 assert.match(x,/const h=unique\(home\),d=unique\("draw"\),a=unique\(away\)/);
 assert.match(x,/latest\.has\(b\.bookmaker\)/);
 assert.match(x,/aligned\.length<2/);
 assert.match(x,/MAX_BOOKMAKER_SPREAD_MS/);
 assert.match(x,/bookmakerPriceVerified|executablePriceVerified:false/);
 assert.match(x,/independentVetoModel:false/);
 assert.match(x,/marketReferenceSelfcheck/);
 assert.doesNotMatch(x,/fetch\(|https:\/\/|placeBet|process\.env|Math\.random/);
});
