import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
test("Paper control proof must have been locked BEFORE kickoff with exact FT source",()=>{
 const x=read("src/lib/research/prospective-market-proof.ts");
 assert.match(x,/p\.lane==="PREMATCH_ODDS_CONTROL"/);
 assert.match(x,/p\.modelVersion==="ODDS_PREMATCH_DEVIG_CONTROL_V1"/);
 assert.match(x,/p\.quoteProvider==="the-odds-api"/);
 assert.match(x,/now>=lock&&lock<starts&&lock>=q&&q>=up/);
 assert.match(x,/starts-lock>=30\*60_000/);
 assert.match(x,/isExactEplFixture/);
 assert.match(x,/confirmForwardPaper/);
 assert.match(x,/persisted\.length===1&&matches\.length===1/);
 assert.match(x,/s\.score\.home===expected\.score\.home/);
 assert.match(x,/s\.provider===expected\.provider/);
 assert.match(x,/firstPerEvent\.has\(p\.eventId\)/);
 assert.match(x,/unreconciledFinals/);
 assert.match(x,/profitableStrategyVerified|profitabilityVerified:false/);
 assert.match(x,/prospectiveMarketProofSelfcheck/);
 assert.doesNotMatch(x,/fetch\(|https:\/\/|process\.env|placeBet|Math\.random/);
});
