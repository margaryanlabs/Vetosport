import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
test("Sportmonks existing scheduled poll must use live scoreboard, NOT ten-second fixture delta",()=>{
 const p=read("src/lib/providers/sportmonks.ts");
 const ing=read("src/lib/ingestion/live-football-state.ts");
 assert.match(p,/getActiveLivescores\(\)/);
 assert.match(p,/"\/livescores"/);
 assert.match(ing,/client\.getActiveLivescores\(\)/);
 assert.doesNotMatch(ing,/getLatestUpdatedFixtures\(\)/);
 assert.match(ing,/liveWindow:"SPORTMONKS_LIVESCORES_ALL_NOT_LATEST_10_SECONDS"/);
 assert.match(p,/include:"participants;state;scores;periods"/);
});
